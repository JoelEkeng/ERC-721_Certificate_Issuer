#!/usr/bin/env bash
# Regenerate the shared TypeScript ABI from Foundry compilation output.
#
# Usage: ./scripts/sync-abi.sh
#
# Prerequisites: run `forge build` in packages/contracts/ first.

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
ARTIFACT="$REPO_ROOT/packages/contracts/out/CertificateIssuer.sol/CertificateIssuer.json"
SHARED_OUTPUT="$REPO_ROOT/packages/web3/src/abi.ts"
FRONTEND_OUTPUT="$REPO_ROOT/apps/web/src/lib/abi.ts"

if [ ! -f "$ARTIFACT" ]; then
  echo "Error: Foundry artifact not found at $ARTIFACT"
  echo "Run 'forge build' in packages/contracts/ first."
  exit 1
fi

# Extract the ABI array and format as TypeScript const
python3 -c "
import json, sys

with open('$ARTIFACT') as f:
    data = json.load(f)

abi_json = json.dumps(data['abi'], indent=2)

print('/**')
print(' * CertificateIssuer contract ABI — extracted from Foundry compilation output.')
print(' * Typed as \`const\` for viem/wagmi type inference.')
print(' *')
print(' * AUTO-GENERATED by scripts/sync-abi.sh — do not edit manually.')
print(' * Regenerate: ./scripts/sync-abi.sh')
print(' */')
print(f'export const certificateIssuerAbi = {abi_json} as const;')
" > "$SHARED_OUTPUT"

# Copy to frontend (Turbopack cannot resolve cross-root re-exports)
cp "$SHARED_OUTPUT" "$FRONTEND_OUTPUT"

ENTRIES=$(python3 -c "import json; print(len(json.load(open('$ARTIFACT'))['abi']))")
echo "ABI synced to $SHARED_OUTPUT ($ENTRIES entries)"
echo "ABI copied to $FRONTEND_OUTPUT"
